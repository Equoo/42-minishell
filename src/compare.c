#include "minishell.h"

int	ft_strcmp(char *s1, char *s2)
{
	size_t	ct;

	ct = 0;
	while (s1[ct] != '\0' && s2[ct] != '\0')
	{
		if (s1[ct] != s2[ct])
			return (s1[ct] - s2[ct]);
		++ct;
	}
	return (s1[ct] - s2[ct]);
}
